export type CatalogGame = {
  name: string
  /** 목록에 적힌 그대로의 인원 표기 (예: "4~8인 이상") */
  players: string
  minPlayers: number
  /** "이상"으로 끝나면 상한 없음 */
  maxPlayers: number | null
  description: string
  /** 표지 이미지 경로. 없으면 null */
  image: string | null
}

// "이름 (인원) - 설명". 이름에 괄호가 들어가도 되게 마지막 "(…인…) - " 를 기준으로 자른다
const LINE = /^(.+?)\s*\(([^()]*인[^()]*)\)\s*-\s*(.+)$/

function parsePlayers(text: string) {
  const numbers = text.match(/\d+/g)?.map(Number) ?? []
  const min = numbers[0] ?? 1
  const openEnded = text.includes('이상')
  const max = openEnded ? null : (numbers[1] ?? min)
  return { minPlayers: min, maxPlayers: max }
}

function parseGames(list: string): CatalogGame[] {
  return list
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .flatMap((line) => {
      const match = LINE.exec(line)
      if (!match) {
        // 형식이 틀린 줄은 빠뜨리지 않게 개발 중에 바로 알린다
        if (import.meta.env.DEV) console.warn('게임 목록 형식이 맞지 않는 줄:', line)
        return []
      }
      const [, name, players, description] = match
      const file = GAME_IMAGES[name]
      return [
        {
          name,
          players,
          ...parsePlayers(players),
          description,
          image: file ? `/games/${file}` : null,
        },
      ]
    })
}

export const GAMES = parseGames(GAME_LIST)

/** 이 인원으로 할 수 있는 게임인지 */
export const supportsPlayers = (game: CatalogGame, count: number) =>
  game.minPlayers <= count && (game.maxPlayers === null || count <= game.maxPlayers)
