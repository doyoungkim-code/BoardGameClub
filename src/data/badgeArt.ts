export const achievementArt = (goal: number) => ACHIEVEMENT_ART[goal] ?? ACHIEVEMENT_ART[1]

/** 칭호 값('auto:<id>' / 'granted:<이름>') → 그림 */
export function titleArt(titleKey: string | null | undefined): Sprite | null {
  if (!titleKey) return null
  if (titleKey.startsWith('auto:')) return TITLE_ART[titleKey.slice(5)] ?? GRANTED_TITLE_ART
  return GRANTED_TITLE_ART
}
